/**
 * توليد اختبار متكامل.
 * @param {object} p { subject, grade, topic, questionCount, difficulty, assessment }
 * @returns {object} { meta, mcqs, essays, totalMarks }
 */
export function generateExam(p) {
  const family = subjectFamily(p.subject);
  const topic = p.topic?.trim() || "الموضوع المطروح";
  const baseBank = mcqBank[family] || mcqBank.general;
  const mcqCount = Math.max(1, Math.min(p.questionCount || 5, 12));

  // بناء أسئلة الاختيار مع إعادة ترتيب الخيارات وتحديث الإجابة الصحيحة
  const mcqs = [];
  for (let i = 0; i < mcqCount; i++) {
    const tpl = baseBank[i % baseBank.length];
    const opts = tpl.options(topic);
    const idxMap = shuffle([0, 1, 2, 3]);
    const shuffledOptions = idxMap.map((o) => opts[o]);
    const newCorrect = idxMap.indexOf(tpl.correct);
    mcqs.push({
      number: i + 1,
      type: "اختيار من متعدد",
      stem: tpl.stem(topic),
      options: shuffledOptions,
      correctIndex: newCorrect,
      marks: 1,
      bloom: tpl.bloom,
      difficulty: tpl.difficulty,
      modelAnswer: tpl.model(topic),
    });
  }

  // سؤالان مقاليان (أو واحد إذا كان العدد الكلي صغيرًا)
  const essayList = (essayBank[family] || essayBank.general)(topic);
  const essays = essayList.slice(0, 2).map((q, i) => ({
    number: mcqCount + i + 1,
    type: "سؤال مقالي",
    stem: q,
    marks: 4,
    bloom: i === 0 ? "التحليل" : "التقويم",
    modelAnswer: (essayModelBank[family] || essayModelBank.general)(topic),
  }));

  const totalMarks = mcqs.reduce((s, q) => s + q.marks, 0) + essays.reduce((s, q) => s + q.marks, 0);

  return {
    meta: {
      type: "اختبار",
      title: `اختبار ${p.assessment || "ختامي"}: ${topic}`,
      subject: p.subject,
      grade: p.grade,
      topic,
      difficulty: p.difficulty || "متدرّج",
      assessment: p.assessment || "ختامي",
      totalMarks,
      timeMinutes: 15 + mcqCount * 3 + essays.length * 10,
      date: new Date().toLocaleDateString("ar-EG", { dateStyle: "long" }),
    },
    mcqs,
    essays,
  };
}


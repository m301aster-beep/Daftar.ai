/**
 * توليد تحضير درس متكامل.
 * @param {object} p { subject, grade, topic, duration }
 */
export function generateLessonPlan(p) {
  const family = subjectFamily(p.subject);
  const topic = p.topic?.trim() || "الموضوع المطروح";
  const strategy = pick(activeStrategies);
  const duration = p.duration || 45;

  // صياغة نواتج التعلم بصياغة سلوكية قابلة للقياس (قابلة للملاحظة + الشرط + المعيار)
  const outcomes = [
    `أن يحدد الطالب ثلاث خصائص لـ"${topic}" بدقة في زمن لا يتجاوز 5 دقائق.`,
    `أن يحلّل الطالب علاقة بين عناصر "${topic}" مع ذكر مثالين على الأقل.`,
    `أن يطبّق الطالب ما تعلّمه في "${topic}" على موقف جديد بنسبة صواب لا تقل عن 80%.`,
  ];

  return {
    meta: {
      type: "تحضير درس",
      title: `تحضير درس: ${topic}`,
      subject: p.subject,
      grade: p.grade,
      topic,
      strategy,
      duration,
      date: new Date().toLocaleDateString("ar-EG", { dateStyle: "long" }),
    },
    sections: {
      objectives: outcomes,
      hook: introHooks[family](topic),
      presentation: explanationSteps[family](topic),
      strategyNote: `استراتيجية التعلم المعتمدة: ${strategy} — مع مراعاة الفروق الفردية بتوزيع الأدوار داخل المجموعات وفق مستويات الطلاب.`,
      enrichment: enrichmentActivities[family](topic),
      assessment: [
        `سؤال اختيار من متعدد يقيس الفهم المباشر لـ"${topic}".`,
        `سؤال مقالي قصير يقيس الاستنتاج من "${topic}".`,
        `ملاحظة سلوك الطلاب أثناء النشاط وسجل أعمال السنة.`,
      ],
    },
  };
}


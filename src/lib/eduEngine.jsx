export function generateWorksheet(p) {
  const family = subjectFamily(p.subject);
  const topic = p.topic?.trim() || "الموضوع المطروح";
  const purpose = p.purpose || "تدريبات حصصية"; // حصصية | واجب منزلي
  const tasks = (worksheetTasks[family] || worksheetTasks.general)(topic);

  return {
    meta: {
      type: "ورقة عمل",
      title: `ورقة عمل (${purpose}): ${topic}`,
      subject: p.subject,
      grade: p.grade,
      topic,
      purpose,
      duration: purpose.includes("واجب") ? "واجب منزلي" : "45 دقيقة",
      date: new Date().toLocaleDateString("ar-EG", { dateStyle: "long" }),
    },
    tasks,
  };
}

// ===================================================================
// نقطة الدخول الموحّدة: توليد حسب نوع الأداة
// ===================================================================
export function generateContent(toolId, params) {
  // محاكاة الزمن الحقيقي للذكاء الاصطناعي عبر Promise
  return new Promise((resolve) => {
    setTimeout(() => {
      if (toolId === "exam") resolve(generateExam(params));
      else if (toolId === "lesson") resolve(generateLessonPlan(params));
      else if (toolId === "worksheet") resolve(generateWorksheet(params));
      else resolve(generateExam(params));
    }, 1600);
  });
}
